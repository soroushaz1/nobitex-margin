// Bundle the ES modules the background runner needs into one plain script.
// The Capacitor background runner executes a single classic script (no imports),
// so we concatenate the modules in dependency order and strip import/export syntax.
// No npm dependencies on purpose.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ORDER = ['util.js', 'indicators.js', 'risk.js', 'nobitex.js', 'market.js', 'ai.js', 'runner-main.js'];

function strip(src, name) {
  let out = src
    // import { a, b } from './x.js';  (single or multi-line)
    .replace(/^import\s[\s\S]*?from\s+['"][^'"]+['"];?\s*$/gm, '')
    // export { a, b };
    .replace(/^export\s*\{[^}]*\};?\s*$/gm, '')
    // export const / function / class / async function
    .replace(/^export\s+(?=(const|let|var|function|class|async)\b)/gm, '');
  if (/^\s*(import|export)\b/m.test(out)) throw new Error(`unsupported import/export left in ${name}`);
  return `// ---- ${name} ----\n${out}`;
}

export function buildRunner() {
  const parts = ORDER.map((f) => strip(readFileSync(join(root, 'www/js', f), 'utf8'), f));
  const code = `// GENERATED by scripts/build-runner.mjs — do not edit.\n'use strict';\n${parts.join('\n')}\n`;
  const outFile = join(root, 'www/runners/background.js');
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, code);
  return outFile;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  console.log('wrote', buildRunner());
}
